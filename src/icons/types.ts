import type { ComponentProps } from 'react'

/**
 * Пропсы любой иконки кита.
 *
 * Расширяют нативный `<svg>`, поэтому наружу проходит всё: `className`, `style`,
 * `onClick`, `aria-*`, `ref` (в React 19 это обычный проп, `forwardRef` не нужен).
 *
 * Цвет иконка берёт из `currentColor`, то есть наследует `color` родителя —
 * отдельного пропа под цвет нет и не должно быть. Исключение — иконки с собственной
 * палитрой (бейдж уведомлений, логотипы платёжных систем): у них цвета зашиты
 * в разметку, часть через токены.
 */
export type IconProps = ComponentProps<'svg'> & {
  /**
   * Сторона квадрата в CSS-пикселях или любая CSS-длина. По умолчанию `24` —
   * `--icon-size-md` дизайн-системы.
   *
   * Задаёт сразу `width` и `height`. Непрямоугольные логотипы (`StripeIcon`,
   * `PaypalIcon` — viewBox 24×16) впишутся в этот квадрат по центру, без растяжения.
   */
  size?: number | string
}
